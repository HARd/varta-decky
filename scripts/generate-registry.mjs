import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const extensionsDir = path.join(__dirname, '../src/extensions');
const registryFile = path.join(extensionsDir, 'registry.ts');

function generateRegistry() {
    const entries = fs.readdirSync(extensionsDir, { withFileTypes: true });
    
    let imports = `// @generated\n// This file is auto-generated by scripts/generate-registry.mjs\n// Do not edit this file manually.\n\nimport type { VartaExtension } from "./types";\n`;
    let arrayContent = `\nexport const EXTENSIONS: VartaExtension[] = [\n`;

    for (const entry of entries) {
        if (entry.isDirectory()) {
            const extPath = path.join(extensionsDir, entry.name);
            const hasIndexTsx = fs.existsSync(path.join(extPath, 'index.tsx'));
            const hasIndexTs = fs.existsSync(path.join(extPath, 'index.ts'));
            
            if (hasIndexTsx || hasIndexTs) {
                const capName = entry.name.charAt(0).toUpperCase() + entry.name.slice(1);
                const varName = `${capName}ModuleExt`;
                imports += `import ${varName} from "./${entry.name}";\n`;
                arrayContent += `  ${varName},\n`;
            }
        }
    }

    arrayContent += `];\n\nexport function getExtensions() {\n  return EXTENSIONS;\n}\n`;

    const finalContent = imports + arrayContent;
    fs.writeFileSync(registryFile, finalContent, 'utf-8');
    console.log('✅ Generated src/extensions/registry.ts');
}

generateRegistry();
